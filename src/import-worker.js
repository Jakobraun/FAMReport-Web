importScripts('./vendor/xlsx-mini-0.20.3.js');
const modules = Promise.all([import('./source-import.mjs'), import('./workbook-codec.mjs'), import('./working-workbook.mjs')]);
self.onmessage = async ({ data }) => {
  try {
    const [source, codec, working] = await modules;
    let result;
    if (data.action === 'csv' || data.action === 'roster') {
      const bytes = new Uint8Array(data.bytes), limit = data.action === 'csv' ? source.LIMITS.csvBytes : source.LIMITS.rosterBytes;
      if (!bytes.length || bytes.length > limit) throw new Error('Choose a nonempty source file no larger than 10 MiB.');
      const digest = new Uint8Array(await crypto.subtle.digest('SHA-256', bytes));
      const info = source.sourceInfo(data.filename, data.modified, [...digest].map(value => value.toString(16).padStart(2, '0')).join(''));
      result = data.action === 'csv' ? source.parseTagCsv(new TextDecoder('utf-8', { fatal: true }).decode(bytes), info, { friendlyNames: data.friendlyNames, siteAliases: data.siteAliases }) : codec.readRosterWorkbook(bytes, info, XLSX);
    } else if (data.action === 'create') {
      const workspace = working.createWorkspace(data.csv, data.roster);
      const bytes = codec.writeWorkingWorkbook(workspace, XLSX);
      // Verify the exact generated bytes before presenting a download or replacing the preview.
      codec.readWorkingWorkbook(bytes, XLSX);
      result = { workspace, bytes: bytes.buffer };
    } else if (data.action === 'read-working') result = codec.readWorkingWorkbook(new Uint8Array(data.bytes), XLSX);
    else if (data.action === 'serialize') {
      const bytes = codec.writeWorkingWorkbook(data.workspace, XLSX);
      codec.readWorkingWorkbook(bytes, XLSX);
      result = { bytes: bytes.buffer };
    }
    else throw new Error('Unknown workbook operation.');
    self.postMessage({ result }, result?.bytes ? [result.bytes] : []);
  } catch (error) { self.postMessage({ error: error.message || 'The file could not be processed.' }); }
};
